//处理数据
function unsign8IntToSign(list){
    for(let i=0;i<list.length;i++){
        const value = list[i];
        // console.log('DEMO_DATA','org:',value);
        if(value >= 0x80){
            // value = (value-0x80)*(-1)
            value = ((~value & 0x000000ff)+1)*-1;
            // console.log('DEMO_DATA','to value:',value);
            list[i]=value;
        }
    }
    return list;
}

function unsign16IntToSign(list){
    for(let i=0;i<list.length;i++){
        const value = list[i];
        // console.log('DEMO_DATA','org:',value);
        if(value >= 0x8000){
            // value = (value-0x80)*(-1)
            value = ((~value & 0x0000ffff)+1)*-1;
            // console.log('DEMO_DATA','to value:',value);
            list[i]=value;
        }
    }
    return list;
}

